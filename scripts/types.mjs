// Regenerates the TypeScript API models from the Rust types (ts-rs).
//
// 1. empties packages/api-types/src/generated (so removed Rust types disappear);
// 2. runs the ts-rs `export_bindings_*` tests, which write one .ts file per type
//    (the output dir comes from TS_RS_EXPORT_DIR in .cargo/config.toml);
// 3. writes generated/index.ts re-exporting every type.
//
// Usage: node scripts/types.mjs            (regenerate)
//        node scripts/types.mjs --check    (regenerate, then fail if git sees changes)
import { spawnSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'packages', 'api-types', 'src', 'generated');

function run(cmd, args) {
  const result = spawnSync(cmd, args, { cwd: root, stdio: 'inherit' });
  if (result.error) throw new Error(`cannot run ${cmd}: ${result.error.message}`);
  if (result.status !== 0) process.exit(result.status ?? 1);
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
run('cargo', ['test', '--workspace', '--quiet', 'export_bindings']);

const types = readdirSync(outDir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.slice(0, -3))
  .sort();
const index =
  '// Generated by scripts/types.mjs (`make types`). Do not edit this file manually.\n' +
  types.map((t) => `export type { ${t} } from './${t}';\n`).join('');
writeFileSync(join(outDir, 'index.ts'), index);
console.info(`types: ${types.length} types in ${relative(root, outDir)}`);

if (process.argv.includes('--check')) {
  const rel = relative(root, outDir);
  const status = spawnSync('git', ['status', '--porcelain', '--', rel], {
    cwd: root,
    encoding: 'utf8'
  });
  if (status.error || status.status !== 0) {
    console.error('types: cannot run git status');
    process.exit(1);
  }
  if (status.stdout.trim() !== '') {
    console.error(
      `types: ${rel} is stale; run \`make types\` and commit the result:\n${status.stdout}`
    );
    process.exit(1);
  }
  console.info('types: up to date');
}
